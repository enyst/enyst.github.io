import { readFile, writeFile } from "node:fs/promises";

// Area pages own their sections. Rebuild compatibility routes after adding IDs.
const pages = JSON.parse(await readFile("arch/agentic-linting-pages.json", "utf8"));
const overview = await readFile("arch/agentic-linting-refactoring.html", "utf8");
const ownIds = new Set([...overview.split("<noscript>")[0].matchAll(/\bid="([^"]+)"/g)].map(match => match[1]));
const destinations = {};
for (const page of pages) {
  const text = await readFile(`arch/${page.file}`, "utf8");
  const article = text.split('<article class="prose">')[1]?.split("</article>")[0];
  if (!article) throw new Error(`Missing article in ${page.file}`);
  for (const [, id] of article.matchAll(/\bid="([^"]+)"/g)) {
    if (id === "rollout" || ownIds.has(id)) continue;
    if (Object.hasOwn(destinations, id)) throw new Error(`Duplicate section ID: ${id}`);
    destinations[id] = `${page.file}#${id}`;
  }
}
const generated = `/* Generated by scripts/build-agentic-linting-navigation.mjs. */
const destinations = ${JSON.stringify(destinations, null, 2)};
function routeLegacyAnchor() {
  let key;
  try { key = decodeURIComponent(location.hash.slice(1)); } catch { return; }
  if (Object.hasOwn(destinations, key)) location.replace(new URL(destinations[key], location.href).href);
}
routeLegacyAnchor();
window.addEventListener("hashchange", routeLegacyAnchor);
`;
const path = "arch/agentic-linting-legacy.js";
if (process.argv.includes("--check")) {
  if (await readFile(path, "utf8") !== generated) throw new Error("Run node scripts/build-agentic-linting-navigation.mjs");
} else {
  await writeFile(path, generated);
}
console.log(`${Object.keys(destinations).length} legacy section routes verified`);
